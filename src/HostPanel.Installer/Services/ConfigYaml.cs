using YamlDotNet.Serialization;
using YamlDotNet.Serialization.NamingConventions;

namespace HostPanel.Installer.Services;

/// <summary>
/// Read/write WizardState as YAML so the operator can save their wizard
/// answers and replay them on sibling boxes via --config FILE --headless.
///
/// camelCase field names match the JSON API at /api/wizard/state for symmetry
/// (operator can copy from the JSON if they prefer that route).
///
/// CachedPreflight is intentionally excluded — it's box-specific snapshot data
/// that means nothing on a different host.
/// </summary>
public static class ConfigYaml
{
    private static ISerializer Serializer() => new SerializerBuilder()
        .WithNamingConvention(CamelCaseNamingConvention.Instance)
        .ConfigureDefaultValuesHandling(DefaultValuesHandling.OmitDefaults | DefaultValuesHandling.OmitNull)
        .DisableAliases()
        .Build();

    private static IDeserializer Deserializer() => new DeserializerBuilder()
        .WithNamingConvention(CamelCaseNamingConvention.Instance)
        .IgnoreUnmatchedProperties()
        .Build();

    public static string Save(WizardState state)
    {
        // Make a copy so we don't mutate the live state during serialization.
        var snapshot = CloneWithoutPreflight(state);
        var yaml = Serializer().Serialize(snapshot);
        return $"""
# HostPanel install configuration — generated by the wizard.
# Replay with:  sudo hostpanel-installer --config THIS_FILE --headless
#
# Secrets (saPassword, adminPassword, cfApiToken, smtpPassword, tailscaleAuthKey,
# backupSecretKey, pairingToken) are written in plaintext. Treat this file as
# sensitive — store in your secrets manager rather than version control.

{yaml}
""";
    }

    public static WizardState Load(string yamlPath)
    {
        if (!File.Exists(yamlPath))
            throw new FileNotFoundException($"Config file not found: {yamlPath}");
        var text = File.ReadAllText(yamlPath);
        var loaded = Deserializer().Deserialize<WizardState>(text)
            ?? throw new InvalidOperationException("YAML parsed to null — file may be empty");
        loaded.LastUpdatedAt = DateTime.UtcNow;
        return loaded;
    }

    private static WizardState CloneWithoutPreflight(WizardState s) => new()
    {
        Role = s.Role,
        SentryOptIn = s.SentryOptIn,
        InstallMssql = s.InstallMssql,
        SaPassword = s.SaPassword,
        CapMssqlMemory = s.CapMssqlMemory,
        MssqlMemoryMb = s.MssqlMemoryMb,
        ExternalDbConnectionString = s.ExternalDbConnectionString,
        Hostname = s.Hostname,
        BindIp = s.BindIp,
        PublicIp = s.PublicIp,
        AutoCreateCfDns = s.AutoCreateCfDns,
        CfApiToken = s.CfApiToken,
        PreValidateDns = s.PreValidateDns,
        Tls = s.Tls,
        SetSystemHostname = s.SetSystemHostname,
        Timezone = s.Timezone,
        InstallChrony = s.InstallChrony,
        CreateSwapfile = s.CreateSwapfile,
        ConfigureUfw = s.ConfigureUfw,
        InstallFail2ban = s.InstallFail2ban,
        AdminSshPublicKey = s.AdminSshPublicKey,
        JoinTailscale = s.JoinTailscale,
        TailscaleAuthKey = s.TailscaleAuthKey,
        ConfigureSmtp = s.ConfigureSmtp,
        SmtpHost = s.SmtpHost,
        SmtpPort = s.SmtpPort,
        SmtpUser = s.SmtpUser,
        SmtpPassword = s.SmtpPassword,
        ConfigureBackups = s.ConfigureBackups,
        BackupDest = s.BackupDest,
        BackupBucketOrPath = s.BackupBucketOrPath,
        BackupAccessKey = s.BackupAccessKey,
        BackupSecretKey = s.BackupSecretKey,
        ForwardToLoki = s.ForwardToLoki,
        LokiEndpoint = s.LokiEndpoint,
        UpdateChannel = s.UpdateChannel,
        UpdateApplyMode = s.UpdateApplyMode,
        PostToN8n = s.PostToN8n,
        N8nWebhookUrl = s.N8nWebhookUrl,
        AdminEmail = s.AdminEmail,
        AdminPassword = s.AdminPassword,
        RecoveryContactEmail = s.RecoveryContactEmail,
        UploadBrandLogo = s.UploadBrandLogo,
        BrandLogoUrl = s.BrandLogoUrl,
        BrandColor = s.BrandColor,
        CreateDemoCustomer = s.CreateDemoCustomer,
        PrefetchAppCatalog = s.PrefetchAppCatalog,
        PrimaryUrl = s.PrimaryUrl,
        PairingToken = s.PairingToken,
        ThisBoxReachableAddress = s.ThisBoxReachableAddress,
        PreferTailscaleForCallback = s.PreferTailscaleForCallback
        // CachedPreflight intentionally omitted
    };
}
